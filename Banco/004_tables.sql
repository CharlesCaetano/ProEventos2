CREATE TABLE ESTOQUE (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  PRODUTO_ID      DM_ID,
  QUANTIDADE      DM_QUANTIDADE,
  CUSTO_MEDIO     DM_VALOR,
  DATA_ATUALIZACAO DM_DATAHORA,
  CONSTRAINT FK_ESTOQUE_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_ESTOQUE_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTO(ID),
  CONSTRAINT UQ_ESTOQUE_PROD UNIQUE (EMPRESA_ID, PRODUTO_ID)
);

CREATE TABLE MOVIMENTO_ESTOQUE (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  PRODUTO_ID      DM_ID,
  TIPO            CHAR(1) NOT NULL CHECK (VALUE IN ('E', 'S', 'A', 'I')),
  /* E=Entrada, S=Saída, A=Ajuste, I=Inventário */
  QUANTIDADE      DM_QUANTIDADE,
  CUSTO_UNITARIO  DM_VALOR,
  DOCUMENTO       VARCHAR(50),
  OBSERVACAO      DM_DESCRICAO,
  USUARIO_ID      DM_ID,
  DATA_MOVIMENTO  DM_DATAHORA,
  CONSTRAINT FK_MOVEST_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_MOVEST_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTO(ID),
  CONSTRAINT FK_MOVEST_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID)
);

