CREATE TABLE EMPRESA (
  ID              DM_ID PRIMARY KEY,
  RAZAO_SOCIAL    DM_NOME,
  NOME_FANTASIA   DM_NOME_NULL,
  CNPJ            DM_CNPJ_CPF,
  IE              DM_IE_RG,
  IM              DM_IE_RG,
  ENDERECO        VARCHAR(200),
  NUMERO          VARCHAR(10),
  COMPLEMENTO     VARCHAR(100),
  BAIRRO          VARCHAR(100),
  CIDADE          VARCHAR(100),
  UF              DM_UF,
  CEP             DM_CEP,
  TELEFONE        DM_TELEFONE,
  EMAIL           DM_EMAIL,
  LOGO            DM_CAMINHO,
  REGIME_TRIBUTARIO SMALLINT DEFAULT 1,
  /* 1=Simples Nacional, 2=Lucro Presumido, 3=Lucro Real */
  STATUS          DM_STATUS,
  DATA_CADASTRO   DM_DATAHORA,
  CRT             SMALLINT DEFAULT 1
);

CREATE TABLE GRUPO (
  ID              DM_ID PRIMARY KEY,
  NOME            DM_NOME,
  DESCRICAO       DM_DESCRICAO,
  STATUS          DM_STATUS,
  DATA_CADASTRO   DM_DATAHORA
);

CREATE TABLE USUARIO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  GRUPO_ID        DM_ID_NULL,
  NOME            DM_NOME,
  LOGIN           VARCHAR(50) NOT NULL,
  SENHA           VARCHAR(255) NOT NULL,
  EMAIL           DM_EMAIL,
  TELEFONE        DM_TELEFONE,
  ADMINISTRADOR   DM_BOOLEAN DEFAULT 'N',
  STATUS          DM_STATUS,
  DATA_CADASTRO   DM_DATAHORA,
  ULTIMO_ACESSO   DM_DATAHORA,
  TOKEN_RESET     VARCHAR(255),
  CONSTRAINT FK_USUARIO_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_USUARIO_GRUPO FOREIGN KEY (GRUPO_ID) REFERENCES GRUPO(ID),
  CONSTRAINT UQ_USUARIO_LOGIN UNIQUE (LOGIN)
);

CREATE TABLE PERMISSAO (
  ID              DM_ID PRIMARY KEY,
  GRUPO_ID        DM_ID,
  MODULO          VARCHAR(50) NOT NULL,
  TELA            VARCHAR(50) NOT NULL,
  PODE_VISUALIZAR DM_BOOLEAN DEFAULT 'N',
  PODE_INSERIR    DM_BOOLEAN DEFAULT 'N',
  PODE_EDITAR     DM_BOOLEAN DEFAULT 'N',
  PODE_EXCLUIR    DM_BOOLEAN DEFAULT 'N',
  PODE_IMPRIMIR   DM_BOOLEAN DEFAULT 'N',
  CONSTRAINT FK_PERMISSAO_GRUPO FOREIGN KEY (GRUPO_ID) REFERENCES GRUPO(ID)
);

CREATE TABLE CONFIGURACAO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CHAVE           VARCHAR(100) NOT NULL,
  VALOR           VARCHAR(500),
  DESCRICAO       DM_DESCRICAO,
  CONSTRAINT FK_CONFIG_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT UQ_CONFIG_CHAVE UNIQUE (EMPRESA_ID, CHAVE)
);

