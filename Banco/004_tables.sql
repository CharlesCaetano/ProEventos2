CREATE TABLE FORMA_PAGAMENTO (
  ID              DM_ID PRIMARY KEY,
  DESCRICAO       DM_NOME,
  TIPO            CHAR(2) DEFAULT 'DI',
  /* DI=Dinheiro, CC=Cartão Crédito, CD=Cartão Débito, CH=Cheque,
     BO=Boleto, PI=PIX, TR=Transferência */
  TEF             DM_BOOLEAN DEFAULT 'N',
  STATUS          DM_STATUS
);

CREATE TABLE CONDICAO_PAGAMENTO (
  ID              DM_ID PRIMARY KEY,
  DESCRICAO       DM_NOME,
  PARCELAS        DM_INTEIRO DEFAULT 1,
  DIAS_ENTRE_PARCELAS DM_INTEIRO DEFAULT 30,
  STATUS          DM_STATUS
);

CREATE TABLE PEDIDO_VENDA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CLIENTE_ID      DM_ID,
  USUARIO_ID      DM_ID,
  NUMERO          DM_INTEIRO,
