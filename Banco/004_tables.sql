CREATE TABLE CAIXA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  USUARIO_ID      DM_ID,
  DATA_ABERTURA   DM_DATAHORA,
  DATA_FECHAMENTO DM_DATAHORA,
  VALOR_ABERTURA  DM_VALOR,
  VALOR_FECHAMENTO DM_VALOR,
  STATUS          CHAR(1) DEFAULT 'A' CHECK (VALUE IN ('A', 'F')),
  /* A=Aberto, F=Fechado */
  OBSERVACOES     DM_TEXTO,
  CONSTRAINT FK_CAIXA_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_CAIXA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID)
);

CREATE TABLE MOVIMENTO_CAIXA (
  ID              DM_ID PRIMARY KEY,
  CAIXA_ID        DM_ID,
  TIPO            CHAR(1) NOT NULL CHECK (VALUE IN ('E', 'S', 'G', 'P')),
  /* E=Entrada(Venda), S=Sangria, G=Suprimento, P=Pagamento */
  VALOR           DM_VALOR,
  DESCRICAO       DM_DESCRICAO,
  PEDIDO_VENDA_ID DM_ID_NULL,
  FORMA_PAGAMENTO_ID DM_ID_NULL,
  DATA_MOVIMENTO  DM_DATAHORA,
  CONSTRAINT FK_MOVCX_CAIXA FOREIGN KEY (CAIXA_ID) REFERENCES CAIXA(ID),
  CONSTRAINT FK_MOVCX_PEDIDO FOREIGN KEY (PEDIDO_VENDA_ID) REFERENCES PEDIDO_VENDA(ID),
  CONSTRAINT FK_MOVCX_FORMAPAG FOREIGN KEY (FORMA_PAGAMENTO_ID) REFERENCES FORMA_PAGAMENTO(ID)
);

/* ============================================================
   MÓDULO: AUDITORIA / LOGS
   ============================================================ */

CREATE TABLE LOG_SISTEMA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  USUARIO_ID      DM_ID,
  TABELA          VARCHAR(50) NOT NULL,
  OPERACAO        CHAR(1) NOT NULL CHECK (VALUE IN ('I', 'U', 'D')),
  /* I=Insert, U=Update, D=Delete */
  REGISTRO_ID     BIGINT,
  DADOS_ANTERIORES DM_TEXTO,
  DADOS_NOVOS     DM_TEXTO,
  IP_ORIGEM       VARCHAR(45),
  DATA_HORA       DM_DATAHORA,
  CONSTRAINT FK_LOG_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_LOG_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID)
);
