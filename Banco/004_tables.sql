/* ============================================================
   MÓDULO: FINANCEIRO
   ============================================================ */

CREATE TABLE FINANCEIRO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  TIPO            CHAR(1) NOT NULL CHECK (VALUE IN ('R', 'P')),
  /* R=Receber, P=Pagar */
  CLIENTE_ID      DM_ID_NULL,
  FORNECEDOR_ID   DM_ID_NULL,
  PEDIDO_VENDA_ID DM_ID_NULL,
  DOCUMENTO       VARCHAR(50),
  DESCRICAO       DM_DESCRICAO,
  VALOR_ORIGINAL  DM_VALOR,
  VALOR_PAGO      DM_VALOR,
  VALOR_DESCONTO  DM_VALOR,
  VALOR_JUROS     DM_VALOR,
  VALOR_MULTA     DM_VALOR,
  DATA_EMISSAO    DM_DATAHORA,
  DATA_VENCIMENTO DM_DATA,
  DATA_PAGAMENTO  DM_DATA,
  STATUS          CHAR(1) DEFAULT 'A' CHECK (VALUE IN ('A', 'P', 'C', 'V')),
  /* A=Aberto, P=Pago, C=Cancelado, V=Vencido */
  FORMA_PAGAMENTO_ID DM_ID_NULL,
  OBSERVACOES     DM_TEXTO,
  CONSTRAINT FK_FIN_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_FIN_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID),
  CONSTRAINT FK_FIN_FORNECEDOR FOREIGN KEY (FORNECEDOR_ID) REFERENCES FORNECEDOR(ID),
  CONSTRAINT FK_FIN_PEDIDO FOREIGN KEY (PEDIDO_VENDA_ID) REFERENCES PEDIDO_VENDA(ID),
  CONSTRAINT FK_FIN_FORMAPAG FOREIGN KEY (FORMA_PAGAMENTO_ID) REFERENCES FORMA_PAGAMENTO(ID)
);

CREATE TABLE CONTA_RECEBER (
